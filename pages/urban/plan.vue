        <h3>計畫摘要:</h3>
        林口特定區計畫第四次通盤檢討（第三階段）案的要點涵蓋了多項土地使用分區的調整、舊有規劃問題的解決，以及對未來發展的人口估算與行政權責的劃分。此案已於中華民國
        114 年 8 月 12 日經內政部都市計畫委員會第 1084
        次會議審議通過，旨在使都市計畫更趨務實與彈性。
        以下為本案的主要變更及檢討內容：

        <h4>1. 土地使用分區及公共設施用地調整</h4>
        <h5>A. 宗教用地合法化及條件調整</h5>
        <ul>
          <li>
            變更與目的：
            本階段納入多處寺廟（如龜山顯安巖祖師廟、五股蓮雲寺、樂善寺、威天宮等）的陳情意見，同意將原屬保護區、農業區或綠化步道用地等變更為「宗教專用區（附）」。此舉旨在輔導既有宗教設施合法化，並考量其現有使用及需求。
          </li>
          <li>
            附帶條件修正： 刪除原訂的
            3年內須取得建築執照及使用執照的時程限制，改為要求地方政府應積極輔導寺方在「下次通盤檢討前」完成相關證件的取得。若屆期未完成，則回復為原土地使用分區。
          </li>
          <li>
            回饋機制：
            變更為宗教專用區（附）的案件，需依規定負擔回饋，方式包括無償捐贈
            20%. 樓地板面積作為公益空間，或捐贈 20%.
            變更面積的土地作為停車空間，或繳納代金擇一辦理。
          </li>
        </ul>

        <h5>B. 學校及文教用地整合 私立學校用地調整：</h5>

        將多處私立學校用地（如私立聖心小學、私立徐匯中學、私立醒吾商專、私立黎明工專等）由「學校用地」變更為「文教區」，並註明其供私立學校使用，以符合公共設施用地不得作為私立學校使用的原則。
        <ul>
          <li>
