          </li>
          <li>
            新增土地使用分區：新增了「考古遺址保存區」、「保存區」、「文教區（特）」及「河川區」等土地使用分區。其中，將原「古蹟保存區」（12.72公頃）調整為「考古遺址保存區」（12.47公頃），以配合文化資產保存法，並依「國定大坌坑考古遺址保存計畫」內容辦理管制。
          </li>
        </ul>

