          </li>
          <li>
            工五工業區變更機制落日：明確規範原工五工業區內乙種工業區申請變更為產業專用區的相關程序及內容，將於民國115
            年 5 月 30日後停止適用，未來如有變更需求，應循都市計畫法定程序辦理。
          </li>
        </ul>

        <h5>D. 土地圖資及權屬爭議處理</h5>

        圖資與樁位校正：
        處理多處因都市計畫圖重製、樁位測定或地籍分割錯誤所導致的土地使用分區邊界不符問題，將錯誤的劃設範圍（如部分高速鐵路用地、捷運系統用地）變更回鄰近分區（如保護區或農業區），以符合實際土地權屬和使用現況。
        <h4>2. 計畫年期與人口目標</h4>
